export function getFullTopicsList() {
  const all = [];
  for (const cat of CATEGORIES) {
    for (let i = 0; i < cat.topics.length; i++) {
      const topicTitle = cat.topics[i];
      const slug = topicTitle
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, '-')
        .replace(/(^-|-$)+/g, '');

      all.push({
        id: `topic-${cat.slug}-${i + 1}`,
        title: topicTitle,
        slug: slug,
        category: cat.name,
        categorySlug: cat.slug,
        baseCategory: cat.baseCategory,
        primaryKeyword: cat.keywords[i % cat.keywords.length] || cat.slug,
        lsiKeywords: cat.keywords,
        status: 'pending' // pending | generated | failed
      });
    }
  }
  return all;
}

export function initializeTopicsQueue() {
  if (fs.existsSync(queueFile)) {
    console.log(`Topics queue already exists with ${JSON.parse(fs.readFileSync(queueFile, 'utf8')).length} topics.`);
    return JSON.parse(fs.readFileSync(queueFile, 'utf8'));
  }

  const topics = getFullTopicsList();
  fs.writeFileSync(queueFile, JSON.stringify(topics, null, 2), 'utf8');
  console.log(`Initialized 500 unique topics (50 per category x 10 categories) in topics-queue.json!`);
  return topics;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  initializeTopicsQueue();
}
